"""30년 경력 수석 방송 시나리오 작가 집필 엔진 (주식 챠트를 뿌셔 보까 전용).

주린이(주식 초보자)도 단 1초 만에 무릎을 치며 이해할 수 있도록,
어려운 전문 금융/차트 용어를 명쾌한 일상 비유와 생생한 스토리텔링으로 완벽하게 '뿌셔'서 풀어냅니다.

[핵심 혁신 3대 원칙]
  1. 종목 맞춤형 드라마 (5대 스토리 아키타입): 붕어빵 템플릿 탈피, 종목 성격에 100% 최적화된 각본
  2. 도파민과 재미 (Entertainment): 찰진 티키타카, 빵 터지는 일상 비유, 사이다 공감 멘트
  3. 확실한 실전 소득 (Actionable Takeaways): "내일 장 열리면 당장 뭘 봐야 하나?" 3대 실전 수칙 제공

6대 국내외 전문 애널리스트 자문단(월가 3인 + 여의도 3인)과 실시간 협의하여,
100% 실측 팩트와 수급 부호는 엄격하게 유지하면서도 가장 재미있고 유익한 명품 대본을 집필합니다.

[수석 집필 작가]
강이현 작가 (지상파 경제 다큐멘터리 메인 작가 & 100만 주식 채널 32년 총괄 작가)
채널 슬로건: "세상에 어려운 차트는 없다! 주식 챠트를 시원하게 뿌셔 보까!"
"""

from __future__ import annotations

from typing import Any, Dict, List


def detect_stock_archetype(m: Dict[str, Any]) -> str:
    """종목의 펀더멘털과 수급/차트 성격에 따라 5대 스토리 아키타입을 자동 분류."""
    pbr = float(m.get("pbr") or 1.0)
    cur_p = float(m.get("cur_price") or m.get("last_close") or 10000)
    high52 = float(m.get("high52") or cur_p * 1.2)
    rsi = float(m.get("rsi") or 50.0)
    f_10d = float(m.get("f_10d") or m.get("foreign_sum") or 0.0)
    i_10d = float(m.get("i_10d") or m.get("inst_sum") or 0.0)

    # 1. 극단적 저평가 턴어라운드 (철강, 지주사, 전통 제조업)
    if pbr < 0.6:
        return "BARGAIN_REVERSAL"
    # 2. 신고가 돌파 / 슈퍼사이클 주도주 (조선, 반도체 탑티어)
    if cur_p >= high52 * 0.88 or (f_10d > 500 and i_10d > 100):
        return "SUPER_CYCLE"
    # 3. 낙폭과대 대형주 / 잠자는 거인의 대반격 (삼성전자, NAVER 등)
    if high52 >= cur_p * 1.3 or rsi < 35.0:
        return "FALLEN_GIANT"
    # 4. 외인·기관 메이저 쌍끌이 매집주
    if f_10d > 0 and i_10d > 0:
        return "SMART_MONEY_INFLOW"
    # 5. 바닥권 턴어라운드 용수철
    return "TURNAROUND_SPRING"


